-- 1. PROFILES TABLE
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL DEFAULT 'Kowsikan',
    email TEXT,
    department TEXT DEFAULT 'Artificial Intelligence & Data Science',
    college TEXT DEFAULT 'S.A. Engineering College',
    role TEXT DEFAULT 'Student',
    avatar_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2. PREDICTION HISTORY TABLE
-- Uses BIGINT GENERATED BY DEFAULT AS IDENTITY to seamlessly allow
-- preserving existing SQLite sequential IDs (1..9) as well as auto-incrementing new ones.
CREATE TABLE IF NOT EXISTS public.prediction_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    analysis_type TEXT DEFAULT 'multimodal',
    rice_variety TEXT NOT NULL,
    temperature REAL NOT NULL,
    humidity REAL NOT NULL,
    moisture_content REAL NOT NULL,
    storage_days REAL NOT NULL,
    has_image BOOLEAN DEFAULT FALSE,
    image_quality TEXT,
    image_confidence REAL,
    detected_variety TEXT,
    tabular_quality TEXT,
    spoilage_risk TEXT,
    shelf_life_days REAL,
    final_quality TEXT,
    overall_confidence REAL,
    recommended_price REAL,
    image_url TEXT
);

-- 3. ENABLE ROW LEVEL SECURITY (RLS)
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.prediction_history ENABLE ROW LEVEL SECURITY;

-- 4. RLS POLICIES (Idempotent)
DROP POLICY IF EXISTS "Allow public read access to profiles" ON public.profiles;
CREATE POLICY "Allow public read access to profiles"
    ON public.profiles FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Allow public insert to profiles" ON public.profiles;
CREATE POLICY "Allow public insert to profiles"
    ON public.profiles FOR INSERT
    WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public update to profiles" ON public.profiles;
CREATE POLICY "Allow public update to profiles"
    ON public.profiles FOR UPDATE
    USING (true);

DROP POLICY IF EXISTS "Allow read access to prediction_history" ON public.prediction_history;
CREATE POLICY "Allow read access to prediction_history"
    ON public.prediction_history FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Allow insert access to prediction_history" ON public.prediction_history;
CREATE POLICY "Allow insert access to prediction_history"
    ON public.prediction_history FOR INSERT
    WITH CHECK (true);

DROP POLICY IF EXISTS "Allow delete access to prediction_history" ON public.prediction_history;
CREATE POLICY "Allow delete access to prediction_history"
    ON public.prediction_history FOR DELETE
    USING (true);

-- 5. STORAGE BUCKETS SETUP
INSERT INTO storage.buckets (id, name, public)
VALUES ('profile-images', 'profile-images', true)
ON CONFLICT (id) DO NOTHING;

INSERT INTO storage.buckets (id, name, public)
