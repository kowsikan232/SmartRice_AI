DROP POLICY IF EXISTS "Public Update for profile-images" ON storage.objects;
CREATE POLICY "Public Update for profile-images"
ON storage.objects FOR UPDATE
USING (bucket_id = 'profile-images');

DROP POLICY IF EXISTS "Public Delete for profile-images" ON storage.objects;
CREATE POLICY "Public Delete for profile-images"
ON storage.objects FOR DELETE
USING (bucket_id = 'profile-images');

